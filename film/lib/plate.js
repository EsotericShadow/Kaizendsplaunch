const isDigit = (c) => c >= "0" && c <= "9";
const jround = roundToInt; // juce::roundToInt (half to even)
const intRect = (x, y, w, h) => toNearestInt([x, y, w, h]); // Rectangle<float>::toNearestInt

// Every readout, so the stage can lay them out again once the fonts have loaded.
const allReadouts = new Set();
export function relayoutReadouts() {
  for (const r of allReadouts) {
    r.key = null;
    if (r.last != null) r.set(r.last);
  }
}

/**
 * One value readout, drawn like LabelWithContainer::paint for a value label in the RC editor:
 * JetBrains Mono SemiBold at the label's JUCE height, every character centred in its own slot
 * (digits share one slot width), the run centred in the inner box (factory panels use
 * Justification::centred), each slot snapped to whole editor px (toNearestInt). Per glyph: eight
 * glow copies, a top and a bottom reflection (squashed, rotated, with four blur copies each), then
 * the glyph. A digit that changes flips over 60 ms: fade, squash to 80 %, shear 0.30.
 */
class Readout {
  constructor(parent, rect, fontH, color, fx, flip) {
    const [x, y, w, h] = rect;
    this.rect = rect;
    this.fontH = fontH;
    this.fx = fx;
    this.flip = flip;
    this.color = color;
    this.inner = [x + 1, y + 1, w - 2, h - 2];
    const font = PLATE_FONTS.mono;
    this.fontCss = `${font.weight} ${+(fontH * font.emPerHeight * KX).toFixed(4)}px "${font.family}"`;
    this.node = el("div", { parent, cls: "cb-readout", style: { position: "absolute", left: "0px", top: "0px", width: "0px", height: "0px", whiteSpace: "pre" } });
    this.cells = [];
    this.last = null;
    this.key = null;
    allReadouts.add(this);
  }

  _adv(ch) {
    return advance(ch, PLATE_FONTS.mono, this.fontH);
  }

  // One text node positioned at an editor-px int rect, centred like Graphics::drawText.
  _textNode(parent) {
    return el("div", {
      parent,
      style: { position: "absolute", left: "0px", top: "0px", textAlign: "center", whiteSpace: "pre", font: this.fontCss, color: this.color },
    });
  }

  // A glyph group: glow (shadows only), top reflection, bottom reflection, glyph.
  _group(parent) {
    const g = { glow: this._textNode(parent), top: this._textNode(parent), bottom: this._textNode(parent), main: this._textNode(parent) };
    g.glow.style.color = "transparent";
    return g;
  }

  _cell(i) {
    while (this.cells.length <= i) {
      const box = el("div", { parent: this.node, style: { position: "absolute", left: "0px", top: "0px", width: "0px", height: "0px", overflow: "visible" } });
      this.cells.push({ box, a: this._group(box), b: this._group(box) });
    }
    return this.cells[i];
  }

  /** Draw one glyph group for character ch in the float area (editor px) at alpha. */
  _drawGroup(g, ch, area, alpha, flipT, boxOrigin) {
    const fx = this.fx;
    const [ax, ay, aw, ah] = area;
    const show = alpha > 0.001;
    for (const n of [g.glow, g.top, g.bottom, g.main]) {
      if (n.__ch !== ch) {
        n.__ch = ch;
        n.textContent = ch;
      }
      setStyle(n, "display", show ? "block" : "none");
    }
    if (!show) return;
    const place = (n, r) => {
      setStyle(n, "left", px(bx(r[0]) - boxOrigin[0]));
      setStyle(n, "top", px(by(r[1]) - boxOrigin[1]));
      setStyle(n, "width", px(r[2] * KX));
      setStyle(n, "height", px(r[3] * KY));
      setStyle(n, "lineHeight", px(r[3] * KY));
    };
    const main = intRect(ax, ay, aw, ah);
    // Glow: eight copies at glowSpread, each rect snapped on its own.
    const s = fx.glowSpread;
    let glow = "";
    if (fx.glowAlpha > 0 && s > 0) {
      const dirs = [[-1, 0], [1, 0], [0, -1], [0, 1], [-0.7, -0.7], [0.7, -0.7], [-0.7, 0.7], [0.7, 0.7]];
      const c = rgba(this.color, alpha * fx.glowAlpha * 0.14);
      glow = dirs
        .map(([dx, dy]) => `${px((jround(ax + dx * s) - main[0]) * KX)} ${px((jround(ay + dy * s) - main[1]) * KY)} 0 ${c}`)
        .join(", ");
    }
    place(g.glow, main);
    setStyle(g.glow, "textShadow", glow);
    // Reflections: squash about the area's bottom (top copy) or top (bottom copy), rotate, blur.
    const refl = (n, spec, pivotBottom) => {
      const [ra, ox, oy, shear, rot] = spec;
      if (!(ra > 0)) {
        setStyle(n, "display", "none");
        return;
      }
      const r = [ax + ox + fx.charDX, ay + oy + fx.charDY, aw, ah];
      const ir = intRect(...r);
      place(n, ir);
      const sy = clamp(1 - fx.squash, 0.08, 1);
      const pivot = [r[0] + r[2] / 2, pivotBottom ? r[1] + r[3] : r[1]];
      setStyle(n, "transformOrigin", `${px((pivot[0] - ir[0]) * KX)} ${px((pivot[1] - ir[1]) * KY)}`);
      // JUCE applies the transform added last first: rotate, then squash, then shear (0 here).
      const sh = shear ? ` skewY(${+Math.atan(shear).toFixed(6)}rad)` : "";
      setStyle(n, "transform", `${sh} scale(1, ${+sy.toFixed(5)}) rotate(${rot}deg)`.trim());
      setStyle(n, "color", rgba(this.color, alpha * ra));
      const b = fx.blur;
      const bc = rgba(this.color, alpha * ra * 0.28);
      const blur = b > 0
        ? [[-1, 0], [1, 0], [0, -1], [0, 1]].map(([dx, dy]) => `${px((jround(r[0] + dx * b) - ir[0]) * KX)} ${px((jround(r[1] + dy * b) - ir[1]) * KY)} 0 ${bc}`).join(", ")
        : "";
      setStyle(n, "textShadow", blur);
    };
    refl(g.top, fx.top, true);
    refl(g.bottom, fx.bottom, false);
    // The glyph, with the flip's squash about its pivot and the shear about the label origin.
    place(g.main, main);
    setStyle(g.main, "opacity", alpha >= 1 ? "" : String(+alpha.toFixed(4)));
    if (flipT) {
      const { scale, pivotBottom, shearSign } = flipT;
      const k = (1 - scale) * this.flip.shear * shearSign;
      const py = pivotBottom ? ay + ah : ay; // label-local pivot is taken in window coords here
      const lx = this.rect[0];
      const ly = this.rect[1];
      // (x, y) -> (x, py + s (y - py) + k (x - lx)) with x, y relative to the label origin.
      setStyle(g.main, "transformOrigin", `${px(bx(lx) - bx(main[0]))} ${px(by(ly) - by(main[1]))}`);
      const f = (py - ly) * (1 - scale) * KY;
      setStyle(g.main, "transform", `matrix(1, ${+(k * (KY / KX)).toFixed(6)}, 0, ${+scale.toFixed(6)}, 0, ${+f.toFixed(4)})`);
    } else {
      setStyle(g.main, "transform", "");
      setStyle(g.main, "transformOrigin", "");
    }
  }

  /** value: "45%" or { text, from, progress } (see Cues.readoutAt). */
  set(value) {
    this.last = value;
    const v = typeof value === "string" ? { text: value, from: value, progress: 1 } : value;
    const flipping = v.from !== v.text && v.progress < 1;
    const p = flipping ? clamp(v.progress) : 1;
    const key = flipping ? `${v.from}>${v.text}@${p.toFixed(4)}` : v.text;
    if (key === this.key) return;
    this.key = key;

    const text = v.text;
    // Map the old digits onto the new text from the right (setAnimatedValueText).
    const mapped = text.split("");
    const flipIdx = new Set();
    let dir = 0;
    if (flipping) {
      const fromD = [];
      const toD = [];
      for (let i = 0; i < v.from.length; i++) if (isDigit(v.from[i])) fromD.push(i);
      for (let i = 0; i < text.length; i++) if (isDigit(text[i])) toD.push(i);
      let fi = fromD.length - 1;
      for (let ti = toD.length - 1; ti >= 0; ti--) {
        const at = toD[ti];
        const fd = fi >= 0 ? v.from[fromD[fi]] : " ";
        mapped[at] = fd;
        if (fd !== text[at]) flipIdx.add(at);
        fi--;
      }
      const num = (s) => {
        const t = s.replace(/[^0-9.-]/g, "");
        return t && t !== "-" && t !== "." ? parseFloat(t) : NaN;
      };
      const a = num(v.from);
      const b = num(text);
      if (Number.isFinite(a) && Number.isFinite(b)) dir = b > a ? 1 : b < a ? -1 : 0;
    }
    const old = mapped.join("");

    // Slot widths (LabelWithContainer::paint), editor px.
    const [ix, iy, iw, ih] = this.inner;
    let digitSlot = 0;
    for (let d = 0; d <= 9; d++) digitSlot = Math.max(digitSlot, this._adv(String(d)));
    digitSlot = Math.max(digitSlot, ih * 0.26);
    const symbolMin = Math.max(ih * 0.16, digitSlot * 0.38);
    const pad = Math.max(0.8, ih * 0.03);
    const slot = (ch) => {
      if (ch === " ") return symbolMin * 0.9;
      const m = this._adv(ch);
      if (isDigit(ch)) return Math.max(digitSlot, m * 1.05) + pad;
      return Math.max(symbolMin, m * 1.3) + pad;
    };
    const widths = [];
    let total = 0;
    for (let i = 0; i < text.length; i++) {
      const w = Math.max(slot(text[i]), slot(i < old.length ? old[i] : text[i]));
      widths.push(w);
      total += w;
    }
    let x = ix + iw / 2 - total / 2; // Justification::centred

    const F = this.flip;
    const minScale = F.minScale;
    for (let i = 0; i < text.length; i++) {
      const w = widths[i];
      const cell = this._cell(i);
      const area = [x, iy, w, ih];
      if (!flipIdx.has(i)) {
        setStyle(cell.box, "overflow", "visible");
        setStyle(cell.box, "left", "0px");
        setStyle(cell.box, "top", "0px");
        setStyle(cell.box, "width", "0px");
        setStyle(cell.box, "height", "0px");
        this._drawGroup(cell.a, text[i], area, 1, null, [0, 0]);
        this._drawGroup(cell.b, " ", area, 0, null, [0, 0]);
      } else {
        // reduceClipRegion(charArea.expanded(0, travel + 2).toNearestInt()) for this character.
        const travelOut = F.travel * F.travelOut;
        const travelIn = F.travel * F.travelIn;
        const clipPad = Math.max(travelOut, travelIn) + 2;
        const clip = intRect(x, iy - clipPad, w, ih + 2 * clipPad);
        const origin = [bx(clip[0]), by(clip[1])];
        setStyle(cell.box, "overflow", "hidden");
        setStyle(cell.box, "left", px(origin[0]));
        setStyle(cell.box, "top", px(origin[1]));
        setStyle(cell.box, "width", px(clip[2] * KX));
        setStyle(cell.box, "height", px(clip[3] * KY));
        const valueDown = dir < 0;
        const outDir = valueDown ? -1 : 1;
        const outArea = [x, iy + outDir * travelOut * p, w, ih];
        const inArea = [x, iy - outDir * travelIn * (1 - p), w, ih];
        this._drawGroup(cell.b, old[i], outArea, 1 - p, { scale: minScale + (1 - minScale) * (1 - p), pivotBottom: !valueDown, shearSign: valueDown ? -1 : 1 }, origin);
        this._drawGroup(cell.a, text[i], inArea, p, { scale: minScale + (1 - minScale) * p, pivotBottom: valueDown, shearSign: valueDown ? 1 : -1 }, origin);
      }
      setStyle(cell.box, "display", "block");
      x += w;
    }
    for (let k = text.length; k < this.cells.length; k++) setStyle(this.cells[k].box, "display", "none");
  }

  clear() {
    this.key = "";
    for (const c of this.cells) setStyle(c.box, "display", "none");
  }
}

// Frame stacks ---------------------------------------------------------------------------------

/**
 * One control drawn from per-frame images: an <img> per frame that the scenes declared, all
 * decoded before frame 0, shown by visibility. Nothing is loaded or decoded during the render, so
 * a seek to any time shows the right frame (never swap img.src per frame).
 */
class FrameStack {
  constructor(parent, urlOf, x, y, w, h, label) {
    this.urlOf = urlOf;
    this.label = label;
    this.node = el("div", { parent, style: { position: "absolute", left: px(x), top: px(y), width: px(w), height: px(h) } });
    this.imgs = new Map();
    this.cur = null;
  }

  require(frames) {
    for (const f of frames) {
      if (this.imgs.has(f)) continue;
      const img = el("img", { parent: this.node, attrs: { src: this.urlOf(f), alt: "", draggable: "false" } });
      Object.assign(img.style, { position: "absolute", left: "0px", top: "0px", width: "100%", height: "100%", visibility: "hidden" });
      this.imgs.set(f, img);
    }
  }

  has(f) {
    return this.imgs.has(f);
  }

  show(f) {
    if (f === this.cur) return;
    if (f != null && !this.imgs.has(f)) {
      throw new Error(`plate: ${this.label} frame ${f} was not prepared; call plate.require()/requireRender() in build()`);
    }
    if (this.cur != null) this.imgs.get(this.cur).style.visibility = "hidden";
    this.cur = f;
    if (f != null) this.imgs.get(f).style.visibility = "";
  }

  setOpacity(a) {
    setStyle(this.node, "opacity", a >= 1 ? "" : String(+a.toFixed(4)));
    setStyle(this.node, "visibility", a > 0 ? "" : "hidden");
  }

  urls() {
    return [...this.imgs.keys()].map((f) => this.urlOf(f));
  }
}

