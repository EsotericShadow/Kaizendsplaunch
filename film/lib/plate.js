const SVGNS = "http://www.w3.org/2000/svg";
function svgEl(tag, attrs, parent) {
  const n = document.createElementNS(SVGNS, tag);
  for (const [k, v] of Object.entries(attrs)) n.setAttribute(k, typeof v === "number" ? String(+v.toFixed(4)) : v);
  if (parent) parent.appendChild(n);
  return n;
}

/**
 * The resize corner: JUCE's ResizableCornerComponent (18 x 18 at 620, 368; LookAndFeel_V2 draws
 * four light/dark line pairs, 1.35 px) and the three grip strokes paintOverChildren adds
 * (#d7d2c6 @ 0.34, 0.75 px). Drawn in editor px inside the body.
 */
function drawCorner(parent) {
  const svg = svgEl("svg", { width: bx(EDITOR_W), height: BODY_PX_H, viewBox: `0 ${HEADER_EDITOR_H} ${EDITOR_W} ${BODY_H}` });
  Object.assign(svg.style, { position: "absolute", left: "0px", top: "0px", overflow: "hidden", pointerEvents: "none" });
  parent.appendChild(svg);
  const [cx, cy, cw, ch] = [620, 368, 18, 18];
  const clip = svgEl("clipPath", { id: `cb-corner-${(drawCorner.n = (drawCorner.n || 0) + 1)}` }, svg);
  svgEl("rect", { x: cx, y: cy, width: cw, height: ch }, clip);
  const g = svgEl("g", { "clip-path": `url(#${clip.id})` }, svg);
  const t = Math.min(cw, ch) * 0.075;
  for (let i = 0; i < 1; i += 0.3) {
    svgEl("line", { x1: cx + cw * i, y1: cy + ch + 1, x2: cx + cw + 1, y2: cy + ch * i, stroke: "#d3d3d3", "stroke-width": t }, g);
    svgEl("line", { x1: cx + cw * i + t, y1: cy + ch + 1, x2: cx + cw + 1, y2: cy + ch * i + t, stroke: "#a9a9a9", "stroke-width": t }, g);
  }
  const size = 7;
  const inset = 5;
  const r = [EDITOR_W - inset - size, 386 - inset - size];
  for (let i = 1; i < 3; i++) {
    const o = (i * size) / 3;
    svgEl("line", { x1: r[0] + size - o, y1: r[1] + size, x2: r[0] + size, y2: r[1] + size - o, stroke: "rgba(215,210,198,0.34)", "stroke-width": 0.75 }, svg);
  }
  return svg;
}

// Plate ---------------------------------------------------------------------------------------

const range = (a, b) => {
  const out = [];
  for (let f = Math.min(a, b); f <= Math.max(a, b); f++) out.push(f);
  return out;
};

// Lever travel inside the switch cell (512 px atlas frames): ball up to ball down, y 87..365
// around the pivot at cell y 226.
const LEVER = { cy: 226 / 512, size: 278 / 512 };

export class Plate {
  /**
   * engine: green | blue | red | purple | black | white (Create).
   * opts: { parent, scale, x, y (window top-left) or cx, cy (window centre), header (default true:
   * the top bar), hiRes (true: also load the prepared 2x backpanel and show it whenever the plate
   * is drawn above scale 1, the shipped 1400 px bitmap otherwise; "always": the 2x plate at any
   * scale; false: never; default: true when the plate is built above scale 1. Pass true for a plate
   * built small that focus() pushes in later: the 2x art is decoded before frame 0 like any image,
   * so it costs about 32 MB of decoded pixels per plate), litPlate ("editor" (default): the lit
   * plate at the 638 x 330 the editor's HQLitOverlay caches it at, magnified like the app, so the
   * HQ-on plate is as soft as in the app; "full": the 1400 px lit bitmap), thumb, readouts, state
   * (initial state; its frames are prepared) }.
   */
  constructor(engine, { parent = null, scale = 1, x = 0, y = 0, cx = null, cy = null, header = true, hiRes = null, litPlate = "editor", thumb = null, readouts = null, className = "", state = null } = {}) {
    if (!RC[engine]) throw new Error(`plate: unknown engine ${engine}`);
    this.engine = engine;
    this.G = RC[engine];
    this.white = engine === "white";
    this.art = artFor(engine);
    const hr = hiRes ?? scale > 1.0001;
    this.hiRes = !this.art.plate2x || !hr ? false : hr === "always" ? "always" : "auto";
    this.showThumb = thumb ?? true;
    this.showReadouts = readouts ?? true;
    this.headerH = header ? HEADER_PX : 0;
    this.width = PLATE_W;
    this.height = BODY_PX_H + this.headerH;

    this.el = el("div", { cls: `cb-plate cb-${engine} ${className}`.trim(), parent });
    Object.assign(this.el.style, { position: "absolute", left: "0px", top: "0px", transformOrigin: "0 0" });
    this.inner = el("div", { parent: this.el });
    Object.assign(this.inner.style, { position: "absolute", left: "0px", top: "0px", width: px(this.width), height: px(this.height), transformOrigin: "0 0", background: "#000000" });
    if (header) {
      this.topbar = new TopBar({
        parent: this.inner,
        k: KX,
        engineName: this.white ? "New Engine" : ENGINE_NAMES[engine],
        placeholder: this.white,
      });
    }
    this.body = el("div", { parent: this.inner, style: { position: "absolute", left: "0px", top: px(this.headerH), width: px(PLATE_W), height: px(BODY_PX_H), overflow: "hidden" } });

    // Backpanel: the shipped bitmap stretched into the body (plus the 2x art for close-ups), the lit
    // plate over it at the lever's lit amount (HQLitOverlay).
    const plateBg = (url, parent) =>
      el("div", {
        parent,
        style: {
          position: "absolute",
          left: "0px",
          top: "0px",
          width: px(PLATE_W),
          height: px(BODY_PX_H),
          backgroundImage: `url("${url}")`,
          backgroundSize: "100% 100%",
          backgroundRepeat: "no-repeat",
        },
      });
    const panel = (key) => {
      const wrap = el("div", { parent: this.body, style: { position: "absolute", left: "0px", top: "0px", width: px(PLATE_W), height: px(BODY_PX_H) } });
      const src = key === "plateOn" && litPlate === "editor" ? this.art.plateOnEditor : this.art[key];
      const lo = plateBg(src, wrap);
      const hi = this.hiRes ? plateBg(this.art.plate2x[key], wrap) : null;
      return { wrap, lo, hi };
    };
    this.plateOff = panel("plateOff");
    this.plateOn = panel("plateOn");
    Object.assign(this.plateOn.wrap.style, { opacity: "0", visibility: "hidden" });

    const rect = ([x0, y0, w, h]) => [bx(x0), by(y0), w * KX, h * KY];
    // Knobs: the _off and _on frames in an isolated group, the _on stack added with plus-lighter,
    // so the group is (1 - t) off + t on in premultiplied colour, which is what the editor's
    // drawCrossfadedFilmstripPair computes pixel by pixel while the HQ lever moves.
    this.knobs = {};
    for (const k of KNOBS) {
      const [kx, ky, w, h] = rect(this.G[k]);
      const group = el("div", { parent: this.body, style: { position: "absolute", left: px(kx), top: px(ky), width: px(w), height: px(h), isolation: "isolate" } });
      const mk = (on) => new FrameStack(group, (f) => this.art.knobFrame(k, on, f), 0, 0, w, h, `${engine} ${k}${on ? " on" : " off"}`);
      const off = mk(false);
      const on = this.white ? null : mk(true);
      if (on) setStyle(on.node, "mixBlendMode", "plus-lighter");
      this.knobs[k] = { off, on };
    }
    {
      const [mx, my, w, h] = rect(this.G.mix);
      this.mix = new FrameStack(this.body, (f) => this.art.mixFrame(f), mx, my, w, h, `${engine} mix`);
    }
    if (this.showThumb && this.art.thumb) {
      // LookAndFeel_V2::getSliderLayout indents a horizontal slider by getSliderThumbRadius
      // (min(12, h / 2)) at each end; drawLinearSlider / drawSliderThumb then draw the thumb at
      // the full height, image aspect (200 x 400), at most 20 % of that width, travelling between
      // 11.5 % insets. drawSliderThumb hands its float x, y, w, h to the int overload of
      // Graphics::drawImage, so the drawn rectangle is truncated to whole editor px (setState).
      const [sx0, sy, sw0, sh] = this.G.color;
      const indent = Math.min(12, Math.floor(sh * 0.5));
      const sx = sx0 + indent;
      const sw = sw0 - 2 * indent;
      const th = sh;
      const tw = Math.min(th * 0.5, sw * 0.2);
      this.thumbGeom = { x0: sx + sw * 0.115, x1: sx + sw - sw * 0.115, w: tw, h: th, y: sy + (sh - th) / 2 };
      this.thumb = el("div", {
        parent: this.body,
        style: {
          position: "absolute",
          top: px(by(Math.trunc(this.thumbGeom.y))),
          width: px(Math.trunc(tw) * KX),
          height: px(Math.trunc(th) * KY),
          backgroundImage: `url("${this.art.thumb}")`,
          backgroundSize: "100% 100%",
          backgroundRepeat: "no-repeat",
        },
      });
      // Until a state sets COLOR, the thumb rests at the factory default (50 %).
      this.thumb.style.left = px(bx(Math.trunc((this.thumbGeom.x0 + this.thumbGeom.x1) / 2 - tw / 2)));
    }
    {
      const [x0, y0, w, h] = rect(this.G.hq);
      // Two stacks, the lever frame under the fractional position and the next one, blended like
      // AnimatedToggleButton::paint ((1 - a) base + a next) in an isolated plus-lighter group.
      const group = el("div", { parent: this.body, style: { position: "absolute", left: px(x0), top: px(y0), width: px(w), height: px(h), isolation: "isolate" } });
      this.sw = [0, 1].map(() => new FrameStack(group, (f) => this.art.switchFrame(f), 0, 0, w, h, `${engine} switch`));
      setStyle(this.sw[1].node, "mixBlendMode", "plus-lighter");
    }
    this.readouts = {};
    if (this.showReadouts) {
      const color = READOUT_COLOR[engine];
      for (const r of READOUTS) {
        const fontH = r === "mix" ? this.G.fontH.mix : r === "color" ? this.G.fontH.color : this.G.fontH.main;
        const flip = r === "mix" ? RC_FLIP.mix : r === "color" ? RC_FLIP.color : RC_FLIP.main;
        this.readouts[r] = new Readout(this.body, this.G.values[r], fontH, color, this.G.fx[r], flip);
      }
    }
    drawCorner(this.body);
    // Everything in the body except the readouts: setGrade() filters these (colour = sound, v5).
    const readoutNodes = new Set(Object.values(this.readouts).map((r) => r.node));
    this._gradeNodes = [...this.body.children].filter((n) => !readoutNodes.has(n));
    this.cur = {};
    this.placement = { x: 0, y: 0, scale: 1, dx: 0, dy: 0 };
    this.place(cx != null ? { cx, cy, scale } : { x, y, scale });
    if (state) {
      this.require(state);
      this.setState(state);
    }
  }

  // Frames this state shows: { knobs: {rate: f,...}, mix: f, switch: [i0, i1], on, off }.
  // Main knobs (every engine and the white sheet): 10 x 10 frames read forward; factory mix: 13 x 12
  // read in reverse; the white mix (1632 px sheet): 10 x 10 read forward (drawRotarySlider).
  _framesOf(state) {
    const out = { knobs: {}, mix: null, sw: [], on: false, off: false };
    for (const k of KNOBS) {
      if (state.frames && state.frames[k] != null) out.knobs[k] = state.frames[k];
      else if (state[k] != null) out.knobs[k] = knobFrameMain(pFromValue(k, state[k]));
    }
    if (state.frames && state.frames.mix != null) out.mix = state.frames.mix;
    else if (state.mix != null) out.mix = this.white ? knobFrameMain(pFromValue("mix", state.mix)) : knobFrameMix(pFromValue("mix", state.mix));
    let sf = state.switchFrame;
    if (sf == null && state.hq != null) sf = state.hq ? SWITCH_ON : SWITCH_OFF;
    if (sf == null && this.white) sf = SWITCH_ON;
    if (sf != null) {
      const f = clamp(sf, 0, 17);
      const i0 = Math.floor(f + 1e-6);
      out.sw = [i0, Math.min(17, i0 + 1)];
      out.frac = f - i0;
      out.lit = 1 - f / 17;
      out.on = out.lit > 1e-4;
      out.off = out.lit < 1 - 1e-4;
    }
    return out;
  }

  /**
   * Prepare the frames a state (or list of states) will show. Call in build(); setState throws on
   * a frame that was not prepared. States without a switch position prepare both HQ sheets.
   */
  require(states) {
    for (const s of [].concat(states)) {
      const fr = this._framesOf(s);
      const both = !fr.sw.length;
      for (const k of KNOBS) {
        if (fr.knobs[k] == null) continue;
        if (fr.off || both || this.white) this.knobs[k].off.require([fr.knobs[k]]);
        if ((fr.on || both) && this.knobs[k].on) this.knobs[k].on.require([fr.knobs[k]]);
      }
      if (fr.mix != null) this.mix.require([fr.mix]);
      if (fr.sw.length) {
        this.sw[0].require([fr.sw[0]]);
        if (fr.frac > 1e-4) this.sw[1].require([fr.sw[1]]);
      }
    }
    return this;
  }

  /** Prepare every frame between two knob frames (a gesture), for one control. */
  requireFrames(control, f0, f1, { on = true, off = true } = {}) {
    const fs = range(f0, f1);
    if (control === "mix") this.mix.require(fs);
    else if (control === "switch") {
      this.sw[0].require(fs);
      this.sw[1].require(fs);
    } else {
      if (off || this.white) this.knobs[control].off.require(fs);
      if (on && this.knobs[control].on) this.knobs[control].on.require(fs);
    }
    return this;
  }

  /**
   * Prepare everything a cue render shows over [t0, t1] (sampled per video frame), e.g.
   * plate.requireRender(cues, "R04", 24, 28) for the Red shot with its HQ flip.
   */
  requireRender(cues, renderId, t0, t1, fps = 480) { // dense: time-warped cuts seek between 1/60 steps
    const n = Math.max(1, Math.round((t1 - t0) * fps));
    const states = [];
    for (let i = 0; i <= n; i++) states.push(cues.settingsAt(renderId, t0 + ((t1 - t0) * i) / n));
    return this.require(states);
  }

  /** The image URLs this plate draws (for preloading). */
  urls() {
    const u = [...new Set([this.plateOff.lo, this.plateOn.lo].map((n) => n.style.backgroundImage.slice(5, -2)))];
    if (this.hiRes) u.push(this.art.plate2x.plateOff, this.art.plate2x.plateOn);
    if (this.art.thumb && this.showThumb) u.push(this.art.thumb);
    for (const k of KNOBS) {
      u.push(...this.knobs[k].off.urls());
      if (this.knobs[k].on) u.push(...this.knobs[k].on.urls());
    }
    u.push(...this.mix.urls(), ...this.sw[0].urls(), ...this.sw[1].urls());
    return [...new Set(u)];
  }

  /**
   * Position on screen (relative to the parent): x/y is the window's top-left (top bar included),
   * or give cx/cy for its centre. dx/dy is an extra offset (G2 drift). Scale is a plain 2D
   * transform: the plate has no canvas inside, so it is seek-safe.
   */
  place({ x, y, cx, cy, scale, dx, dy } = {}) {
    const P = this.placement;
    if (scale != null) P.scale = scale;
    if (cx != null) P.x = cx - (this.width * P.scale) / 2;
    else if (x != null) P.x = x;
    if (cy != null) P.y = cy - (this.height * P.scale) / 2;
    else if (y != null) P.y = y;
    if (dx != null) P.dx = dx;
    if (dy != null) P.dy = dy;
    setStyle(this.el, "left", px(P.x));
    setStyle(this.el, "top", px(P.y));
    setStyle(this.el, "width", px(this.width * P.scale));
    setStyle(this.el, "height", px(this.height * P.scale));
    setStyle(this.el, "transform", P.dx || P.dy ? `translate(${px(P.dx)}, ${px(P.dy)})` : "");
    setStyle(this.inner, "transform", P.scale === 1 ? "" : `scale(${+P.scale.toFixed(6)})`);
    this._pickArt();
    return this;
  }

  // The product's plates up to scale 1, the 2x art above it. The unlit 2x plate reduces to the
  // shipped bitmap, so it switches at scale 1 invisibly; the lit 2x plate is sharper than the
  // editor's 638 px lit cache, so it fades in over scale 1.0 to 1.25 instead of popping.
  _pickArt() {
    if (!this.hiRes) return;
    const s = this.placement.scale * (this.outerScale || 1);
    const always = this.hiRes === "always";
    const offHi = always || s > 1.0001;
    const onA = always ? 1 : clamp((s - 1) / 0.25);
    const key = `${offHi}:${onA.toFixed(4)}`;
    if (key === this._hiKey) return;
    this._hiKey = key;
    setStyle(this.plateOff.lo, "visibility", offHi ? "hidden" : "");
    setStyle(this.plateOff.hi, "visibility", offHi ? "" : "hidden");
    setStyle(this.plateOn.lo, "visibility", onA >= 1 ? "hidden" : "");
    setStyle(this.plateOn.hi, "visibility", onA > 0 ? "" : "hidden");
    setStyle(this.plateOn.hi, "opacity", onA >= 1 ? "" : String(+onA.toFixed(4)));
  }

  /**
   * If the plate's parent is itself scaled (a camera group), tell the plate the extra factor so
   * that hiRes "auto" picks the art for the true on-screen scale.
   */
  setOuterScale(s) {
    this.outerScale = s;
    this._pickArt();
    return this;
  }

  /**
   * Close-up camera: place the plate at `zoom` (plate scale) with a control ("rate", "mix", "hq",
   * "color", "rateValue", ...) or a body point [x, y] (plate px) at the screen point `at` (parent
   * coordinates; default: where that point is now). Returns the placement. Knob frames are native
   * up to KNOB_NATIVE_SCALE (1.08) and magnified above it; the mix knob (512 px frames), readouts,
   * top bar and HQ lever stay sharp far beyond 2x; the backpanel switches to its 2x art above 1.
   */
  focus({ on, zoom, at = null, dx = 0, dy = 0 }) {
    let bxy;
    if (Array.isArray(on)) bxy = on;
    else if (typeof on === "string" && on.endsWith("Value")) {
      const [x, y, w, h] = this.G.values[on.slice(0, -5)];
      bxy = [bx(x + w / 2), by(y + h / 2)];
    } else {
      const r = this.controlRect(on);
      bxy = [r.cx, r.cy];
    }
    const target = at ?? this.toScreen(bxy[0], bxy[1]);
    const s = zoom ?? this.placement.scale;
    const x = target[0] - bxy[0] * s;
    const y = target[1] - (this.headerH + bxy[1]) * s;
    return this.place({ x, y, scale: s, dx, dy });
  }

  /** Body plate px -> screen px in the parent's coordinates, with the current placement. */
  toScreen(pxX, pxY) {
    const P = this.placement;
    return [P.x + P.dx + pxX * P.scale, P.y + P.dy + (this.headerH + pxY) * P.scale];
  }

  /** A control's centre and size in body plate px ({ cx, cy, size }). */
  controlRect(name) {
    const G = this.G;
    if (name === "color" || name === "thumb") {
      const i = Math.min(12, Math.floor(G.color[3] * 0.5));
      const w0 = G.color[2] - 2 * i;
      const t = this.thumbGeom || { x0: G.color[0] + i + w0 * 0.115, x1: G.color[0] + i + w0 * 0.885, w: G.color[3] * 0.5, h: G.color[3], y: G.color[1] };
      const cxE = this.cur.thumbCx ?? (t.x0 + t.x1) / 2;
      return { cx: bx(cxE), cy: by(t.y + t.h / 2), size: Math.max(t.w * KX, t.h * KY) };
    }
    if (name === "hq") {
      const [x, y, w, h] = G.hq;
      return { cx: bx(x + w / 2), cy: by(y + h * LEVER.cy), size: w * LEVER.size * KX };
    }
    const [x, y, w, h] = G[name];
    return { cx: bx(x + w / 2), cy: by(y + h / 2), size: w * KX };
  }

  /** A control's centre and size in screen px ({ cx, cy, size }), for rings and camera moves. */
  controlScreenRect(name) {
    const r = this.controlRect(name);
    const [cx, cy] = this.toScreen(r.cx, r.cy);
    return { cx, cy, size: r.size * this.placement.scale };
  }

  /**
   * Colour = sound (v5): a CSS filter saturate(sat) brightness(bright) on the plate body (backpanel,
   * knobs, mix, thumb, lever), never on the readouts, which keep the product's own colour. The
   * plate has no canvas, so the filter is seek-safe. topBar: also grade the top bar (default true).
   * keep: names of the readouts left ungraded (default: all six).
   */
  setGrade({ sat = 1, bright = 1, topBar = true, keep = null } = {}) {
    const f = sat === 1 && bright === 1 ? "" : `saturate(${+sat.toFixed(4)}) brightness(${+bright.toFixed(4)})`;
    for (const n of this._gradeNodes) setStyle(n, "filter", f);
    // keep: the readouts that stay in their own colour (default all of them), e.g. ["mix"].
    for (const [name, r] of Object.entries(this.readouts)) setStyle(r.node, "filter", !keep || keep.includes(name) ? "" : f);
    if (this.topbar && this.topbar.el) setStyle(this.topbar.el, "filter", topBar ? f : "");
    return this;
  }

  /**
   * state: { rate, depth, offset, width, color, mix } in display units (any subset),
   * hq (0/1) or switchFrame (0..17, float while the lever moves),
   * readouts: { rate: "0.60 Hz" | { text, from, progress }, ... } to override the text
   * (default: formatted from the values), frames: { rate: 47, mix: 78 } to force filmstrip frames.
   * Cues.plateStateAt(render, t) returns exactly this shape.
   */
  setState(state) {
    const c = this.cur;
    const fr = this._framesOf(state);
    if (fr.sw.length) {
      const key = `${fr.sw[0]}:${fr.frac.toFixed(4)}`;
      if (c.sw !== key) {
        c.sw = key;
        c.lit = fr.lit;
        this.sw[0].show(fr.sw[0]);
        const a = fr.frac > 1e-4 ? fr.frac : 0;
        this.sw[0].setOpacity(1 - a);
        this.sw[1].show(a > 0 ? fr.sw[1] : null);
        this.sw[1].setOpacity(a);
        // Lit plate follows the lever: 1 - frame / 17 (AnimatedToggleButton::getAnimationProgress).
        setStyle(this.plateOn.wrap, "opacity", String(+fr.lit.toFixed(4)));
        setStyle(this.plateOn.wrap, "visibility", fr.lit > 1e-4 ? "" : "hidden");
      }
    }
    const lit = c.lit ?? 0;
    for (const k of KNOBS) {
      const f = fr.knobs[k];
      const kn = this.knobs[k];
      // (1 - lit) off + lit on, premultiplied (see the constructor): lit 0 and 1 show one sheet.
      const onA = kn.on ? lit : 0;
      const offA = kn.on ? 1 - lit : 1;
      if (f != null) {
        if (offA > 0) kn.off.show(f);
        if (kn.on && onA > 0) kn.on.show(f);
      }
      kn.off.setOpacity(offA);
      if (kn.on) kn.on.setOpacity(onA);
    }
    if (fr.mix != null) this.mix.show(fr.mix);
    if (this.thumb && state.color != null) {
      const t = this.thumbGeom;
      const cxE = t.x0 + clamp(pFromValue("color", state.color)) * (t.x1 - t.x0);
      if (c.thumbCx !== cxE) {
        c.thumbCx = cxE;
        this.thumb.style.left = px(bx(Math.trunc(cxE - t.w / 2)));
      }
    }
    if (this.showReadouts) {
      for (const r of READOUTS) {
        const o = state.readouts && state.readouts[r];
        if (o != null) this.readouts[r].set(o);
        else if (state[r] != null) this.readouts[r].set(formatReadout(r, state[r]));
      }
    }
    if (state.trim != null && this.topbar && this.topbar.setTrim) this.topbar.setTrim(state.trim);
    return this;
  }
}

/** createPlate("green", opts) or createPlate(stateWithEngine, opts) (prepares and shows that state). */
export function createPlate(engineOrState, opts = {}) {
  if (typeof engineOrState === "string") return new Plate(engineOrState, opts);
  return new Plate(engineOrState.engine, { ...opts, state: engineOrState });
}

/** G2 plate drift in px: A sin(2 pi cycles), A = 4 px x min(1, Depth / 30%). */
export function driftPx(settings, amp = 4) {
  return amp * Math.min(1, settings.depth / 30) * Math.sin(TAU * settings.cycles);
}
